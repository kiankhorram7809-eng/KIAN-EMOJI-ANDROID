# KIAN EMOJI ANDROID

A Persian Android keyboard with voice typing, semantic understanding, emotion detection, and smart sticker suggestions.

## Project Goals

- Persian keyboard with a complete typing layout
- Voice-to-text input
- Persian sentence meaning detection
- Emotion recognition from text
- Context-aware sticker suggestions
- KIAN CLUB custom sticker collection
- Android Input Method Editor (IME) support

## Main Features

### 1. Persian Keyboard
A native Android keyboard designed for Persian typing.

### 2. Voice Typing
Convert Persian speech into text using Android speech recognition.

### 3. Smart Meaning Detection
Analyze typed Persian sentences and identify their intent.

### 4. Emotion Detection
Recognize common emotions such as happiness, sadness, anger, and affection.

### 5. Smart Stickers
Suggest relevant KIAN CLUB stickers based on the meaning and emotion of a message.

## Technology

- Kotlin
- Android SDK
- Android Input Method Service
- Gradle
- Material Design

